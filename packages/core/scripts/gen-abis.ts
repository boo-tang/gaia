// Writes the ABIs of the Gaia contracts as typed TypeScript (`as const`) into src/abis/.
//
// The source is the Hardhat build output, artifacts/contracts/<Name>.sol/<Name>.json at the root
// of the repository. Run `yarn hardhat compile` first.
//
//   yarn workspace @gaia/core abis          writes the files
//   yarn workspace @gaia/core abis:check    fails if a file is not the same as the artifacts
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const CONTRACTS = [
  'GaiaAuction',
  'GaiaCountries',
  'GaiaSquares',
  'GaiaCountryAccount',
  'GaiaLandSale',
  'GaiaCountryMarket',
];

const packageDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = path.resolve(packageDir, '..', '..');
const artifactsDir = path.join(repoRoot, 'artifacts', 'contracts');
const outDir = path.join(packageDir, 'src', 'abis');

const HEADER = '// Generated by scripts/gen-abis.ts from artifacts/. Do not edit.\n';

// GaiaAuction -> gaiaAuctionAbi
const abiName = (contract: string) => `${contract[0].toLowerCase()}${contract.slice(1)}Abi`;

const readAbi = (contract: string): unknown[] => {
  const file = path.join(artifactsDir, `${contract}.sol`, `${contract}.json`);
  if (!fs.existsSync(file)) {
    throw new Error(`${path.relative(repoRoot, file)} not found. Run "yarn hardhat compile" first.`);
  }
  return JSON.parse(fs.readFileSync(file, 'utf8')).abi;
};

const files = new Map<string, string>();
for (const contract of CONTRACTS) {
  const abi = JSON.stringify(readAbi(contract), undefined, 2);
  files.set(`${contract}.ts`, `${HEADER}\nexport const ${abiName(contract)} = ${abi} as const;\n`);
}
files.set('index.ts', `${HEADER}\n${CONTRACTS.map(c => `export { ${abiName(c)} } from './${c}';`).join('\n')}\n`);

const check = process.argv.includes('--check');
const stale: string[] = [];
if (!check) {
  fs.mkdirSync(outDir, { recursive: true });
}
for (const [name, content] of files) {
  const file = path.join(outDir, name);
  if (check) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : undefined;
    if (current !== content) {
      stale.push(name);
    }
  } else {
    fs.writeFileSync(file, content);
  }
}

if (check && stale.length > 0) {
  console.error(
    `These ABI files are not the same as the artifacts: ${stale.join(', ')}.\n` +
      'Run "yarn hardhat compile" and "yarn workspace @gaia/core abis", then commit the files.',
  );
  process.exit(1);
}
console.log(check ? 'The ABI files are up to date.' : `Wrote ${files.size} files to src/abis/.`);
