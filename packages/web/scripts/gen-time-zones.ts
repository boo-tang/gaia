// Writes src/map/time-zones.ts: the main city of each IANA time zone, for the first map view.
//
//   node --experimental-strip-types scripts/gen-time-zones.ts [path of zone.tab]
//
// The input is `zone.tab` of the IANA time zone database (default /usr/share/zoneinfo/zone.tab).
// Browsers give the time zone with the names of ICU, and ICU keeps old names (for example
// `Asia/Calcutta` for `Asia/Kolkata`). So the table also has each ICU name of a zone.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const input = process.argv[2] ?? '/usr/share/zoneinfo/zone.tab';
const output = join(import.meta.dirname, '..', 'src', 'map', 'time-zones.ts');

// `+DDMM`, `+DDMMSS`, `+DDDMM` or `+DDDMMSS` to degrees.
const toDegrees = (text: string, degreeDigits: number) => {
  const sign = text.startsWith('-') ? -1 : 1;
  const digits = text.slice(1);
  const degrees = Number(digits.slice(0, degreeDigits));
  const minutes = Number(digits.slice(degreeDigits, degreeDigits + 2));
  const seconds = Number(digits.slice(degreeDigits + 2) || '0');
  return Math.round(sign * (degrees + minutes / 60 + seconds / 3600) * 100) / 100;
};

const zones = new Map<string, [number, number]>();
for (const line of readFileSync(input, 'utf8').split('\n')) {
  if (line.startsWith('#') || line.trim() === '') {
    continue;
  }
  const [, coordinates, zone] = line.split('\t');
  const match = /^([+-]\d+)([+-]\d+)$/.exec(coordinates);
  if (match === null) {
    throw new Error(`Cannot read the coordinates of ${zone}: ${coordinates}`);
  }
  zones.set(zone, [toDegrees(match[1], 2), toDegrees(match[2], 3)]);
}

for (const [zone, point] of [...zones]) {
  const icuName = new Intl.DateTimeFormat('en', { timeZone: zone }).resolvedOptions().timeZone;
  if (!zones.has(icuName)) {
    zones.set(icuName, point);
  }
}

const rows = [...zones]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([zone, [lat, lng]]) => `  '${zone}': [${lat}, ${lng}],`);
writeFileSync(
  output,
  `// Generated by scripts/gen-time-zones.ts from the IANA zone.tab. Do not edit.
// Time zone -> [latitude, longitude] of its main city.
export const TIME_ZONES: Readonly<Record<string, readonly [number, number]>> = {
${rows.join('\n')}
};
`,
);
console.log(`Wrote ${zones.size} time zones to ${output}`);
